"""Generate docs/SAMPLE_QUERIES.md by actually running the questions.

The submission asks for the queries we ran against stored output. Writing
them by hand would be a claim; running them and capturing the real SQL,
rows and answers makes it evidence.

  python evals/capture_queries.py
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from app.llm import RunBudget  # noqa: E402
from app.nlq import ask  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent

QUESTIONS = [
    ("The brief's own example", "How many shipments were flagged for review this week?"),
    ("Queue triage", "Which documents need an amendment, and how many discrepancies does each have?"),
    ("Where the agent struggles", "Which field fails validation most often?"),
    ("Confidence by field", "What is the average confidence for each field across all runs?"),
    ("Cost control", "How much have we spent on LLM calls in total, and on which models?"),
    ("Trust surface", "Show me every field that could not be read reliably, with its document."),
    ("Latency outlier", "Which document took the longest to process?"),
    ("Audit trail", "Show me every decision with its lowest field confidence and whether an email was sent."),
]


def main() -> int:
    budget = RunBudget(max_calls=100, max_usd=1.0)
    out = [
        "# Sample queries against stored output",
        "",
        "Generated by `python evals/capture_queries.py` — every SQL statement and row",
        "below was produced by the natural-language query layer against the SQLite",
        "database after running the three sample documents through the pipeline.",
        "",
        "The layer is guarded in four ways: the prompt asks for a single read-only",
        "`SELECT`; a static guard rejects anything that is not one statement starting",
        "`SELECT`/`WITH` and blocks write/DDL/PRAGMA keywords; the connection is opened",
        "`mode=ro` so writes are physically impossible; and a `LIMIT` is injected if the",
        "model did not write one. Answers are phrased by a model but every number in",
        "them is checked against the returned rows, falling back to a plain rendering of",
        "the result set if a figure is unsupported.",
        "",
        "---",
        "",
    ]

    for label, q in QUESTIONS:
        print(f"  asking: {q}")
        try:
            r = ask(q, budget=budget)
        except Exception as exc:
            out += [f"### {label}", "", f"**Q:** {q}", "", f"_failed: {exc}_", "", "---", ""]
            continue

        out += [f"### {label}", "", f"**Q:** {q}", "", f"**A:** {r.answer}", "", "```sql",
                r.sql, "```", ""]
        if r.rows:
            cols = r.columns
            out.append("| " + " | ".join(cols) + " |")
            out.append("|" + "|".join("---" for _ in cols) + "|")
            for row in r.rows[:10]:
                cells = ["" if v is None else str(v) for v in row]
                out.append("| " + " | ".join(cells) + " |")
            if r.row_count > 10:
                out.append("")
                out.append(f"_… {r.row_count - 10} more row(s)_")
        else:
            out.append("_no rows matched_")
        if r.warnings:
            out += [""] + [f"> warning: {w}" for w in r.warnings]
        out += ["", f"_{r.latency_ms} ms · ${r.usd_cost:.5f}_", "", "---", ""]

    out += [f"**Total for this capture:** {budget.calls} LLM calls, ${budget.usd:.5f}."]

    dest = ROOT / "docs" / "SAMPLE_QUERIES.md"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"\nwrote {dest.relative_to(ROOT)}  ({budget.calls} calls, ${budget.usd:.5f})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
